def read(name):
    with open(root / name, encoding='utf-8') as f:
        return f.read()


def translate(text, table):
    for he, en in sorted(table, key=lambda pair: len(pair[0]), reverse=True):
        text = text.replace(he, en)
    return text


def generate():
    """Return {filename: text} for every generated English file (newline-normalized)."""
    out = {}
    source = translate(read('capture-flow-he.js'), pairs)
    # Keep Hebrew numeric arithmetic and canonical side values; display English folio notation.
    source = source.replace("photo.folio=photo.daf+' Side '+photo.amud;", "photo.folio=folio({layout:'single',daf:photo.daf,amud:photo.amud});")
    source = source.replace("photo.folio=photo.daf+' עמוד '+photo.amud;", "photo.folio=folio({layout:'single',daf:photo.daf,amud:photo.amud});")
    source = source.replace('href="guide.html"', 'href="guide-en.html"')
    source = source.replace("{layout:'spread',daf:'יב',amud:'ב',next_daf:'יג',next_amud:'א'}:{layout:'single',daf:'12'", "{layout:'spread',daf:'12',amud:'ב',next_daf:'13',next_amud:'א'}:{layout:'single',daf:'12'")
    out['capture-flow-en.js'] = HEADER + source
    for name in ['photo-files', 'drive-backup']:
        text = translate(read(name + '.js'), extra if name == 'photo-files' else extra + pairs)
        text = text.replace("this.folder('Manuscripts','root')", "this.folder('כתבי יד','root')")
        out[name + '-en.js'] = text
    manifest = json.loads(read('manifest.webmanifest'))
    manifest.update(id='./iphone.html', name='Manuscript Photos', short_name='Manuscripts', lang='en', dir='ltr', start_url='./iphone.html')
    out['manifest-iphone.webmanifest'] = json.dumps(manifest, ensure_ascii=False)
    return out


def encode(text):
    # The generated files use CRLF on every platform, matching the deployed files.
    return text.replace('\r\n', '\n').replace('\n', '\r\n').encode('utf-8')


