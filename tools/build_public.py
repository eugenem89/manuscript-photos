ALLOWED = {
    '.gitignore', '.nojekyll', 'README.md', 'app-bootstrap.js', 'capture-flow-en.js', 'capture-flow-he.js',
    'capture-subjects.js', 'demo-page.png', 'drive-backup-en.js', 'drive-backup.js', 'drive-config.json',
    'guide-en.html', 'guide.html', 'icon-192.png', 'icon-512.png', 'index.html', 'iphone.html',
    'libraries-he.json', 'manifest-iphone.webmanifest', 'manifest.webmanifest', 'photo-files-en.js',
    'photo-files.js', 'privacy.html', 'style.css', 'sw.js', 'terms.html',
    'tools/build_public.py', 'tools/watermark.test.cjs', 'watermark-protocol.js', '.github/workflows/public-check.yml',
}
IGNORED = {'.git', '__pycache__', '.DS_Store', 'Thumbs.db'}


def check(generated):
    errors = []
    fail = errors.append

    files = {p.relative_to(root).as_posix() for p in root.rglob('*')
             if p.is_file() and not IGNORED.intersection(p.relative_to(root).parts)}
    for name in sorted(files - ALLOWED):
        fail(f'{name}: not part of the public site (private-edition or stray file?)')
    for name in sorted(ALLOWED - files - {'.github/workflows/public-check.yml'}):
        fail(f'{name}: missing')
    if errors:
        return errors

    for name, text in generated.items():
        if (root / name).read_bytes() != encode(text):
            fail(f'{name}: differs from what tools/build_public.py generates (edit the Hebrew source and rebuild)')

    # Entry pages: standard edition, CSP, bootstrap only.
    for name, manifest in [('index.html', 'manifest.webmanifest'), ('iphone.html', 'manifest-iphone.webmanifest')]:
        html = read(name)
        tag = re.search(r'<html\b[^>]*>', html)
        if not tag or 'data-edition="friend"' not in tag.group(0):
            fail(f'{name}: <html> must carry data-edition="friend" (the standard edition)')
        if 'personal' in html:
            fail(f'{name}: mentions "personal"')
        csp = re.search(r'<meta http-equiv="Content-Security-Policy" content="([^"]+)"', html)
        if not csp:
            fail(f'{name}: Content-Security-Policy meta tag missing')
        else:
            for directive in ["default-src 'self'", "object-src 'none'", "base-uri 'none'"]:
                if directive not in csp.group(1):
                    fail(f'{name}: CSP lacks {directive}')
        if re.findall(r'<script\b[^>]*\bsrc="([^"]+)"', html) != ['app-bootstrap.js'] or html.count('<script') != 1:
            fail(f'{name}: must load app-bootstrap.js and no other script')
        if f'href="{manifest}"' not in html:
            fail(f'{name}: must link {manifest}')

    # The only switch into personal mode is ManuscriptApp.personal, set by the bootstrap.
    boot = read('app-bootstrap.js')
    if not re.search(r'\bpersonal=false[,;]', boot):
        fail('app-bootstrap.js: personal must be the literal false')
    for marker in ["'personal'||", "==='personal'", 'dataset.edition', "'/iphone.html'", 'appearance.js', 'jszip']:
        if marker in boot:
            fail(f'app-bootstrap.js: contains {marker!r}, a personal-edition switch or asset')
    for name in ['capture-flow-he.js', 'capture-flow-en.js']:
        flow = read(name)
        if flow.count('const personal=globalThis.ManuscriptApp?.personal??false;') != 1 or len(re.findall(r'\bpersonal\s*=', flow)) != 1:
            fail(f'{name}: personal must come only from ManuscriptApp.personal')
        if 'photoOnly:!personal' not in flow:
            fail(f'{name}: Drive must be photo-only outside personal mode (photoOnly:!personal)')
        # Renaming these would orphan photos already stored on phones.
        if "(personal?'manuscript-photos-connected-v1':'manuscript-photos-personal-v1')" not in flow:
            fail(f'{name}: IndexedDB database names changed')

    for name in ['drive-backup.js', 'drive-backup-en.js']:
        scopes = set(re.findall(r'https://www\.googleapis\.com/auth/[\w.]+', read(name)))
        if scopes != {'https://www.googleapis.com/auth/drive.file'}:
            fail(f'{name}: Google scope must be drive.file only, found {sorted(scopes)}')

    config = json.loads(read('drive-config.json'))
    if set(config) != {'client_id'} or not str(config['client_id']).endswith('.apps.googleusercontent.com'):
        fail('drive-config.json: must hold only the public client_id')

    sw = read('sw.js')
    if not re.search(r"^const CACHE='manuscript-photos-v\d+';", sw, re.M):
        fail("sw.js: CACHE must be 'manuscript-photos-v<number>'")
    listed = re.search(r'^const FILES=(\[.*?\]);', sw, re.M)
    if not listed:
        fail('sw.js: FILES list not found')
    else:
        for name in json.loads(listed.group(1).replace("'", '"')):
            if name != './' and name not in files:
                fail(f'sw.js: precaches {name}, which is not in the public site')
    if 'ignoreSearch:true' not in sw:
        fail('sw.js: offline fallback must ignore the query string (index.html?lang=en)')

    for name in ['guide.html', 'guide-en.html', 'privacy.html', 'terms.html']:
        text = read(name).lower()
        for word in ['personal edition', 'friend edition', 'tailscale', 'dashboard import']:
            if word in text:
                fail(f'{name}: mentions {word!r}, which the public app does not have')
    return errors


def main():
    generated = generate()
    if '--check' not in sys.argv[1:]:
        for name, text in generated.items():
            data = encode(text)
            if (root / name).read_bytes() != data:
                (root / name).write_bytes(data)
                print('wrote', name)
    errors = check(generated)
    for error in errors:
        print('FAIL', error)
    if errors:
        sys.exit(1)
    print('public build OK:', len(generated), 'generated files current; standard edition only')


if __name__ == '__main__':
    main()
